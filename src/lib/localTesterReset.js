export function clearLocalTesterTutorialState() {
  if (typeof window === 'undefined') return;
  Object.keys(window.localStorage)
    .filter((key) => key.startsWith('local-tutorial:'))
    .forEach((key) => window.localStorage.removeItem(key));
}
