export function isLocalTesterProfile(profile) {
  return [profile?.nickname, profile?.username, profile?.created_by, profile?.name, profile?.display_name]
    .some((value) => String(value || '').trim().toLowerCase().replace(/\s+/g, '_') === 'local_tester')
    || String(profile?.telegram_id || profile?.telegramId || '') === '777000';
}

