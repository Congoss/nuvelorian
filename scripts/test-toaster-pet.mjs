import assert from 'node:assert/strict';
import { advanceToasterAnimation as step, hideToasterBread as hide, newToasterAnimation as initial, toasterBreadPose as pose, TOASTER_TIMINGS } from '../src/lib/toasterPetAnimation.js';
let state = initial();
assert.equal(pose(state).y, 100);
assert.equal(pose(state).heat, 1);
const apex = pose(step(state, TOASTER_TIMINGS.rise + TOASTER_TIMINGS.spin / 2));
assert.equal(apex.y, -69);
assert(Math.abs(apex.rotation - 180) < 1e-10);
assert.equal(apex.heat, 0);
assert.equal(apex.lever, 0);
assert(TOASTER_TIMINGS.rise <= 240 && TOASTER_TIMINGS.fall <= 280, 'Launch and landing must stay brisk');
assert(TOASTER_TIMINGS.spin >= 650, 'Airborne turn must remain readable');
const spinStart = pose(step(state, TOASTER_TIMINGS.rise));
const spinEnd = pose(step(state, TOASTER_TIMINGS.rise + TOASTER_TIMINGS.spin));
assert.equal(spinStart.rotation, 0);
assert.equal(spinEnd.rotation, 360);
assert.equal(spinStart.y, -65);
assert.equal(spinEnd.y, -65);
const landed = pose({ ...state, elapsed: TOASTER_TIMINGS.popping });
assert.equal(landed.rotation, 360);
assert(Math.abs(landed.y - 100) < 1e-10);
for (const fraction of [.28, .4, .6, .72]) {
  const flying = pose(step(state, TOASTER_TIMINGS.popping * fraction));
  assert(flying.y + 145 < 125, 'Full slice must clear the slot during its turn');
}
state = step(state, TOASTER_TIMINGS.popping, () => .5);
assert.equal(state.phase, 'hidden');
assert.equal(state.duration, 45000);
assert.equal(pose(state).heat, 1);
assert.equal(pose(state).lever, 1);
assert.strictEqual(hide(state), state, 'Repeated clicks must not extend the hidden timer');
state = step(state, 44999, () => .5);
assert.equal(state.phase, 'hidden');
state = step(state, 1, () => .5);
assert.equal(state.phase, 'popping');
const duringJump = step(initial(), 160);
const pressed = hide(duringJump);
assert.equal(pose(pressed).y, pose(duringJump).y, 'Click must not teleport a moving toast');
assert.equal(pose(pressed).rotation, pose(duringJump).rotation);
assert.equal(step(pressed, 440, () => 0).duration, TOASTER_TIMINGS.hiddenMin);
assert(step(pressed, 440, () => .999999).duration < TOASTER_TIMINGS.hiddenMax);
for (let ms = 0; ms < TOASTER_TIMINGS.popping; ms += 8) for (const value of Object.values(pose(step(initial(), ms)))) assert(Number.isFinite(value));
console.log('PASS: full 360 turn above slot, reinsertion, heat/lever sync, 30–60s cooking, click continuity.');
