import assert from 'node:assert/strict';
import {randomUUID} from 'node:crypto';
import {marketCommand,marketState} from '../server/services/local-market.js';
import {configureAgents,runAgentTurn,proposeActions,analyzeMarket,treasuryState} from '../server/services/market-agents.js';
import {FALLBACK_PL4_USD,usdToHundredths} from '../src/lib/marketPricing.js';
// Deterministic, in-memory rehearsal. No keys, HTTP, live quotes or saved games.
for(const key of ['MARKET_AGENTS_ENABLED','MARKET_AGENT_MIN_ACCOUNT_DAYS','MARKET_AGENT_MIN_SELLER_LEVEL','MARKET_AGENT_RESALE_DAYS','MARKET_AGENT_SELLS_PER_PLAYER_DAY','MARKET_AGENTS_DAILY_USD','MARKET_AGENT_MAX_BUY_USD','MARKET_AGENT_FORGE_COST_RATIO'])delete process.env[key];
const eq=id=>({id,type:'equipment',slot:id.split('_').at(-1),count:1});
const person=(id,items=[])=>({id,nickname:id,level:100,created_at:'2026-01-01T00:00:00Z',inventory_items:items,equipped_items:{},local_market_p4:usdToHundredths(100)});
const seller=person('Demo player',[eq('night_disinfector_weapon'),eq('nuvelor_boots')]),buyer=person('Second player');
const retailBuyer=person('Retail customer');
const store={players:[seller,buyer,retailBuyer,person('smith'),person('hunter')],local_market_pl4_usd:FALLBACK_PL4_USD};
const [smith,hunter]=configureAgents(store,['smith','hunter'],2);
const persist=()=>true,options={env:{},persist};
const command=(p,body)=>marketCommand(store,p,{requestId:randomUUID(),...body},true,{persist});
const total=()=>store.players.reduce((sum,p)=>sum+p.local_market_p4,0);
const start=total();
console.log('LOCAL SIMULATION · no blockchain transactions · illustrative fixed P4/USD quote');
smith.inventory_items.push(eq('night_disinfector_weapon'));
await command(smith,{action:'list',itemId:'night_disinfector_weapon',price:usdToHundredths(.5)});
await command(retailBuyer,{action:'buy',lotId:smith.local_market_lots.find(l=>l.status==='active'&&l.item.id==='night_disinfector_weapon').id});
console.log('0. A real simulated retail purchase creates exactly one replacement allowance.');
const cheap=usdToHundredths(.2);
await command(seller,{action:'list',itemId:'night_disinfector_weapon',price:cheap});
assert.equal((await runAgentTurn(store,hunter,options)).action,'buy');
console.log('1. Hunter replaces the sold item, within 80% of net retail proceeds.');
await command(seller,{action:'list',itemId:'nuvelor_boots',price:cheap});
assert(!proposeActions(store,hunter,analyzeMarket(store)).some(a=>a.action==='buy'));
console.log('2. A second sale by the same player is rejected by the daily seller limit.');
smith.inventory_items=[];
assert.equal((await runAgentTurn(store,smith,options)).action,'craft');
assert.equal((await runAgentTurn(store,smith,options)).action,'list');
const lot=smith.local_market_lots.find(l=>l.status==='active');
const purchase={action:'buy',lotId:lot.id,requestId:randomUUID()};
await marketCommand(store,seller,purchase,true,{persist});
const after=seller.local_market_p4;
await marketCommand(store,seller,purchase,true,{persist});
assert.equal(seller.local_market_p4,after);
console.log('3. Smith supplies a missing piece; player buys it. Replaying payment does not charge twice.');
await command(seller,{action:'list',itemId:lot.item.id,price:1});
const resale=seller.local_market_lots.find(l=>l.status==='active'&&l.item.id===lot.item.id);
await command(buyer,{action:'buy',lotId:resale.id});
await command(buyer,{action:'list',itemId:lot.item.id,price:1});
assert(!proposeActions(store,hunter,analyzeMarket(store)).some(a=>a.action==='buy'));
console.log('4. Passing an agent-sold item through another player never permits bot buyback.');
assert.equal(total(),start);assert.equal(marketState(store,seller,true).withdrawalEnabled,false);
const treasury=treasuryState(store);
console.log('5. Test-P4 is conserved; treasury stock uses actual cost, free-forged stock has zero cost.');
console.log(JSON.stringify({mode:'simulation',onChainTransfers:0,withdrawalsEnabled:false,atomicJournalEntries:store.local_market_journal.length,dailySpentHundredths:store.local_market_agent_ledger.spent,treasuryCostBasisHundredths:treasury.stock},null,2));
